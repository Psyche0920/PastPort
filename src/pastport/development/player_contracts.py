"""Export TypeScript declarations and the JSON schemas used by player components."""

import argparse
import json
from pathlib import Path
from typing import cast

from pydantic import JsonValue

from pastport.application.player_preparation import PlayerComponentCommand, PlayerComponentResult
from pastport.application.player_runtime import PlayerRuntimeCommand
from pastport.domain.game import ActionResult

DIRECTORY = Path(__file__).resolve().parents[1] / "player"


def schema_object(value: JsonValue) -> dict[str, JsonValue]:
    if not isinstance(value, dict):
        raise ValueError("A schema must be an object")
    return value


def typescript(value: JsonValue) -> str:
    schema = schema_object(value)
    reference = schema.get("$ref")
    if isinstance(reference, str):
        return reference.rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    enumeration = schema.get("enum")
    if isinstance(enumeration, list):
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in enumeration)
    for key in ("anyOf", "oneOf"):
        choices = schema.get(key)
        if isinstance(choices, list):
            return "(" + " | ".join(typescript(item) for item in choices) + ")"
    kind = schema.get("type")
    if kind == "array":
        return "ReadonlyArray<" + typescript(schema["items"]) + ">"
    if kind == "object":
        properties = schema_object(schema.get("properties", {}))
        required = schema.get("required", [])
        if not isinstance(required, list):
            raise ValueError("Required property list is invalid")
        fields = [
            "readonly "
            + json.dumps(name)
            + ("" if name in required else "?")
            + ": "
            + typescript(item)
            for name, item in properties.items()
        ]
        return "{ " + "; ".join(fields) + " }"
    if kind in ("integer", "number"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return str(kind)
    raise ValueError("Unsupported schema construct in player type export")


def check_schema_vocabulary(value: JsonValue) -> None:
    schema = schema_object(value)
    supported = {
        "$defs",
        "$ref",
        "additionalProperties",
        "anyOf",
        "const",
        "default",
        "discriminator",
        "enum",
        "exclusiveMinimum",
        "items",
        "maxItems",
        "maxLength",
        "maximum",
        "minItems",
        "minLength",
        "minimum",
        "oneOf",
        "pattern",
        "properties",
        "required",
        "title",
        "type",
    }
    if set(schema) - supported or schema.get("type") == "number":
        raise ValueError("Schema vocabulary is unsupported by the player validator")
    if "additionalProperties" in schema and schema["additionalProperties"] is not False:
        raise ValueError("Player object schemas must explicitly reject unknown fields")
    for key in ("properties", "$defs"):
        for child in schema_object(schema.get(key, {})).values():
            check_schema_vocabulary(child)
    if "items" in schema:
        check_schema_vocabulary(schema["items"])
    for key in ("anyOf", "oneOf"):
        children = schema.get(key, [])
        if not isinstance(children, list):
            raise ValueError("Schema branches must be arrays")
        for child in children:
            check_schema_vocabulary(child)


def generated() -> dict[str, str]:
    models = (PlayerComponentCommand, PlayerComponentResult, PlayerRuntimeCommand, ActionResult)
    schemas: dict[str, JsonValue] = {}
    definitions: dict[str, JsonValue] = {}
    for model in models:
        schema = cast(dict[str, JsonValue], model.model_json_schema())
        check_schema_vocabulary(schema)
        schemas[model.__name__] = schema
        for name, value in schema_object(schema.get("$defs", {})).items():
            if name in definitions and definitions[name] != value:
                raise ValueError("Conflicting generated player definitions")
            definitions[name] = value
    header = "// Generated by python -m pastport.development.player_contracts; do not edit.\n"
    declaration = (
        header
        + "\n".join(
            "export type " + name + " = " + typescript(value) + ";"
            for name, value in sorted((definitions | schemas).items())
        )
        + "\n"
    )
    wire = (
        header
        + "export const schemas = "
        + json.dumps(schemas, ensure_ascii=False, indent=2, sort_keys=True)
        + ";\n"
    )
    return {
        "contracts.d.ts": declaration,
        "generated-schemas.mjs": wire,
        "runtime.d.mts": header
        + 'import type { PlayerRuntimeCommand, ActionResult } from "./contracts";\n'
        + "export function applyAction(command: PlayerRuntimeCommand): Promise<ActionResult>;\n",
        "preparation.d.mts": header
        + 'import type { PlayerComponentCommand, PlayerComponentResult } from "./contracts";\n'
        + "export function prepare(command: PlayerComponentCommand): "
        "Promise<PlayerComponentResult>;\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for name, contents in generated().items():
        path = DIRECTORY / name
        if options.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit("Generated player contracts are stale: " + name)
        else:
            path.write_text(contents)
    print(
        "Player preparation contracts match Python models."
        if options.check
        else "Player preparation contracts generated."
    )


if __name__ == "__main__":
    main()
