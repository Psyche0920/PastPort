"""Check the standalone document tool; lint and strict typing are separate commands."""

from __future__ import annotations

import ast
import re
from pathlib import Path
from urllib.parse import unquote, urlsplit


class RepositoryChecker:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    @staticmethod
    def anchors(text: str) -> set[str]:
        explicit = set(re.findall(r'<(?:a|h[1-6])\b[^>]*\bid=["\']([^"\']+)', text))
        counts: dict[str, int] = {}
        for heading in re.findall(r"^#{1,6}\s+(.+?)\s*#*\s*$", text, re.MULTILINE):
            slug = re.sub(r"[^\w\- ]", "", heading.lower()).replace(" ", "-")
            count = counts.get(slug, 0)
            counts[slug] = count + 1
            explicit.add(slug if count == 0 else f"{slug}-{count}")
        return explicit

    def run(self) -> tuple[str, ...]:
        issues: list[str] = []
        required = (
            "README.md",
            "pyproject.toml",
            "uv.lock",
            "grant.example.json",
            "src/pastport_evidence/cli.py",
            "docs/technical/PRD_PDF_EVIDENCE_REVIEW.md",
        )
        for name in required:
            if not (self.root / name).is_file():
                issues.append(f"Missing required file: {name}")
        if (self.root / "src/pastport").exists():
            # Generated bytecode from an older checkout is not application source.
            if any((self.root / "src/pastport").rglob("*.py")):
                issues.append("Unrelated main application source remains")
        for folder in ("src", "tools"):
            for path in (self.root / folder).rglob("*.py"):
                try:
                    ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
                except (OSError, UnicodeError, SyntaxError) as error:
                    issues.append(f"{path.relative_to(self.root)}: {type(error).__name__}")
        documents = [self.root / "README.md", self.root / "AGENTS.md"]
        documents.extend((self.root / "docs").rglob("*.md"))
        for path in documents:
            if not path.is_file():
                continue
            text = path.read_text(encoding="utf-8")
            for value in re.findall(r"\[[^\]]*\]\(([^)]+)\)", text):
                parsed = urlsplit(value.strip("<>"))
                if parsed.scheme or parsed.netloc:
                    continue
                target = (path.parent / unquote(parsed.path)).resolve() if parsed.path else path
                if not target.is_relative_to(self.root) or not target.is_file():
                    issues.append(f"{path.relative_to(self.root)}: missing local link {value}")
                elif parsed.fragment and target.suffix == ".md":
                    if unquote(parsed.fragment) not in self.anchors(target.read_text()):
                        issues.append(f"{path.relative_to(self.root)}: missing anchor {value}")
        return tuple(issues)


def main() -> int:
    issues = RepositoryChecker(Path(__file__).resolve().parents[1]).run()
    for issue in issues:
        print(issue)
    if not issues:
        print("Standalone document repository checks passed")
    return 1 if issues else 0


if __name__ == "__main__":
    raise SystemExit(main())
