/** Offline lifecycle checks for the original synthetic reference plugin. */
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { initialize, reduce, result, serialize, restore, validateConfig } from './examples/game/plugins/pastport.match-pairs/1.0.0/logic.mjs';
const bundleUrl = new URL('./examples/game/bundle.json', import.meta.url);
const bundle = JSON.parse(await readFile(bundleUrl, 'utf8'));
const draft = JSON.parse(await readFile(new URL(bundle.entrypoints.narrative_draft, bundleUrl), 'utf8'));
const config = draft.package.game.scenes.flatMap((scene) => scene.tasks).find((task) => task.kind === 'plugin').config;
const context = Object.freeze({ attempt_id: 'fixture-attempt', seed: 'fixture-seed', active_elapsed_ms: 0 });
const initial = initialize(config, context);
assert.equal(result(config, initial).status, 'running');
const wrong = reduce(config, initial, { type: 'select_pair', left_id: 'flour', right_id: 'insufficient' }, context);
assert.equal(wrong.state.attempts, 1);
assert.equal(wrong.result.status, 'running');
assert.equal(initial.attempts, 0);
assert.ok(Object.isFrozen(wrong.state));
assert.throws(() => reduce(config, initial, { type: 'declare_win' }, context));
assert.throws(() => reduce(config, initial, { type: 'select_pair', left_id: 'unknown', right_id: 'kitchen' }, context));
assert.throws(() => validateConfig({ pairs: [config.pairs[0], config.pairs[0]] }));
const partial = reduce(config, wrong.state, { type: 'select_pair', left_id: 'flour', right_id: 'kitchen' }, context);
const restored = restore(config, serialize(config, partial.state), context);
assert.deepEqual(restored, partial.state);
const repeated = reduce(config, restored, { type: 'select_pair', left_id: 'flour', right_id: 'kitchen' }, context);
assert.deepEqual(repeated.state, restored);
const complete = reduce(config, restored, { type: 'select_pair', left_id: 'stock', right_id: 'insufficient' }, context);
assert.deepEqual(complete.result, { status: 'completed', outcome: 'passed', score: 2 });
assert.throws(() => restore(config, JSON.stringify({ attempts: 0, matched_left_ids: ['flour'] }), context));
assert.throws(() => restore(config, JSON.stringify({ attempts: 1, matched_left_ids: [], unknown: true }), context));
assert.deepEqual(restore(config, serialize(config, complete.state), context), complete.state);
console.log('PASS reference plugin: deterministic actions, completion, immutability, repeat, restore and rejection cases.');
console.log('No host integration or browser interaction was exercised.');
