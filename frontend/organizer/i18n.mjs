export function translate(value, locale = language, exactOnly = false) {
  if (!['en','tr'].includes(locale) || typeof value !== 'string') return value;
  const catalog=locale==='tr'?turkishMessages:messages;
  const trimmed = value.trim();
  if (Object.hasOwn(messages, trimmed)) return value.replace(trimmed, catalog[trimmed]);
  const templates = [
    [/^(.+) · 当前第 (\d+) 版$/u, '$1 · current version $2'],
    [/^第 (\d+) 版（当前）$/u, 'Version $1 (current)'],
    [/^第 (\d+) 版$/u, 'Version $1'],
    [/^PDF 来源对象(.*)$/u, 'PDF source object$1'],
    [/^照片 (\d+) · 对象 (\d+)$/u, 'Photo $1 · Object $2'],
    [/^历史评价（(\d+) 次）$/u, 'Review history ($1 entries)'],
    [/^VR编号 (\d+) · 显示文字版本 (.*)$/u, 'Object $1 · Display text version $2'],
    [/^类别：(.*?)；父对象：(.*?)；出现 (\d+) 次。坐标为左上原点的归一化选区。$/u,
      'Category: $1; Parent: $2; Observations: $3. Coordinates are normalized with a top-left origin.'],
  ];
  const trTemplates=['$1 · geçerli sürüm $2','Sürüm $1 (geçerli)','Sürüm $1', 'PDF kaynak nesnesi$1','Fotoğraf $1 · Nesne $2','İnceleme geçmişi ($1 kayıt)','Nesne $1 · Görüntü metni sürümü $2','Kategori: $1; Üst nesne: $2; Gözlem: $3. Koordinatlar sol üst köşeye göre normalize edilmiştir.'];
  for (const [index,[pattern,replacement]] of templates.entries()) if(pattern.test(trimmed))return value.replace(trimmed,trimmed.replace(pattern,locale==='tr'?trTemplates[index]:replacement));
  if(exactOnly)return value;
  return value.replace(/第 (\d+) 版/gu,locale==='tr'?'sürüm $1':'version $1').replace(fragments,match=>catalog[match]);
}
