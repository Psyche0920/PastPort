// Keep the original text per node. No HTML replacement, form reset or data writes on language changes.
export function mountLocalization(doc, {exactOnly = false, protectedSelector = ''} = {}) {
  const sources = new WeakMap();
  const protectedTags = 'script,style,textarea,pre,code,[data-no-i18n]';
  const excluded = protectedSelector ? protectedTags + ',' + protectedSelector : protectedTags;
  function localize(node, key, read, write) {
    const current = read();
    const state = sources.get(node) || {};
    const old = state[key];
    const original = old && current === old.rendered ? old.original : current;
    const rendered = translate(original, language, exactOnly);
    state[key] = {original, rendered}; sources.set(node, state);
    if (current !== rendered) write(rendered);
  }
  function render() {
    doc.documentElement.lang = language === 'zh' ? 'zh-CN' : language;
    const walker = doc.createTreeWalker(doc.body, 4);
    while(walker.nextNode()) {
      const node = walker.currentNode;
      if (!node.parentElement?.closest(excluded)) localize(node, 'text', () => node.data, value => {node.data = value;});
    }
    for (const node of doc.querySelectorAll('[placeholder],[title],[aria-label],[alt]')) {
      if (node.closest('[data-no-i18n]')) continue;
      for (const attribute of ['placeholder','title','aria-label','alt']) if (node.hasAttribute(attribute))
        localize(node, attribute, () => node.getAttribute(attribute), value => node.setAttribute(attribute,value));
    }
    const select = doc.getElementById('interface-language');
    if (select) select.value = language;
  }
  const observer = new doc.defaultView.MutationObserver(render);
  observer.observe(doc.body, {subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['placeholder','title','aria-label','alt']});
  mounted.add(render); render();
  return () => {observer.disconnect();mounted.delete(render);};
}

